/**
 * 精读用的提示词。
 *
 * 要解决的问题：普通 AI 问答会脱离论文泛泛而谈，读者拿到的是"通用知识"，
 * 不是"这篇论文里的答案"。所以这里的约束全都围绕**锚定原文**：
 *   - 先在原文里找依据，答不出来就明说这篇没讲，不许用常识糊过去
 *   - 补充背景是允许的，但必须标清楚"这是背景，不是本文内容"，不能混在一起
 *   - 遇到生僻概念主动补一两句，因为读者卡住的往往不是论文本身而是前置知识
 */

const FIELD_HINT = `先从标题、摘要、术语判断这篇属于哪个领域（如 NLP / CV / 推荐系统 / 生物医学 / 材料 / 经济学…），
然后用**这个领域的惯用表达**回答，不要用泛泛的"人工智能"式措辞。`;

export function buildPaperQaPrompt({ title, context, history, question }) {
  return `你是论文精读助手。读者正在读一篇具体的论文，你的回答必须**贴着这篇论文**，不是泛泛的知识问答。

论文：《${title}》
${FIELD_HINT}

论文内容（长文只截取了前面部分）：
<<<
${context}
>>>
${history ? `\n之前的问答：\n${history}\n` : ''}
读者的问题：${question}

回答规则（按重要性排序）：
1. **先在原文里找依据。** 找到了就答，并指出依据在哪（小节名、图表号，或引用原句的关键片段）。
2. **原文没讲的，直接说"这篇没有讲"**，不要用常识补一个听起来合理的答案冒充论文观点。
3. 说完之后，如果补充背景对理解有帮助，可以补 —— 但必须**另起一段并标明「背景补充（非本文内容）」**。
4. 问题里出现读者可能不熟的概念（专有名词、方法名、数据集、评价指标），**主动用一两句话解释清楚**，不要假设读者懂。这是读者明确要求的。
5. 不要复述摘要，不要说"这篇论文主要研究了……"这种正确的废话。直接回答被问的东西。
6. 篇幅克制：能三句话说清就不要写五段。读者要的是读懂这一处，不是一篇综述。

用中文回答，纯文本，不要 markdown 标题。`;
}

export function buildPaperReportPrompt({ title, context }) {
  return `你是严谨的论文精读助手。请只根据下面这篇论文的原文，生成一份给初学者看的结构化分析报告。

论文：《${title}》
${FIELD_HINT}

论文全文文本（可能来自 PDF 文本层；每段带有页码提示）：
<<<
${context}
>>>

要求：
1. 所有结论都要尽量指出原文依据，例如页码、小节、图表或实验名称；原文没有明确说明就写“原文未说明”，不要猜。
2. “方法”要解释关键机制，不要只罗列模块名；“证据”要区分作者报告的结果和你的推断。
3. 术语用大白话解释，并说明它在本文中具体做什么；不要给脱离本文的百科式解释。
4. 给读者 3-6 条可执行的下一步建议，优先解决读者最可能卡住的地方。
5. 只输出一个 JSON 对象，不要 markdown 代码块，不要额外说明：
{"oneLine":"一句话总结",
 "researchQuestion":"研究问题与动机，指出原文依据",
 "method":"核心方法与关键机制，指出原文依据",
 "data":"数据集、数据规模、预处理或任务设置，原文没有说明就写未说明",
 "experiments":"实验设计、baseline、指标和关键结果，指出图表/章节依据",
 "conclusion":"作者结论与适用范围",
 "limitations":["作者承认或原文可直接看出的局限，每条带依据"],
 "terms":[{"term":"术语","plain":"大白话解释","inPaper":"它在本文中的作用"}],
 "quickAdvice":["给读者的下一步学习建议"],
 "confidence":"high|medium|low，并说明文本是否完整"}`;
}

