/**
 * 精读用的提示词。
 *
 * 要解决的问题：普通 AI 问答会脱离论文泛泛而谈，读者拿到的是"通用知识"，
 * 不是"这篇论文里的答案"。所以这里的约束全都围绕**锚定原文**：
 *   - 先在原文里找依据，答不出来就明说这篇没讲，不许用常识糊过去
 *   - 补充背景是允许的，但必须标清楚"这是背景，不是本文内容"，不能混在一起
 *   - 遇到生僻概念主动补一两句，因为读者卡住的往往不是论文本身而是前置知识
 */

const FIELD_HINT = `先从标题、摘要、术语判断这篇属于哪个领域（如 NLP / CV / 推荐系统 / 生物医学 / 材料 / 经济学…），
然后用**这个领域的惯用表达**回答，不要用泛泛的"人工智能"式措辞。`;

export function buildPaperQaPrompt({ title, context, history, question }) {
  return `你是论文精读助手。读者正在读一篇具体的论文，你的回答必须**贴着这篇论文**，不是泛泛的知识问答。

论文：《${title}》
${FIELD_HINT}

论文内容（长文只截取了前面部分）：
<<<
${context}
>>>
${history ? `\n之前的问答：\n${history}\n` : ''}
读者的问题：${question}

回答规则（按重要性排序）：
1. **先在原文里找依据。** 找到了就答，并指出依据在哪（小节名、图表号，或引用原句的关键片段）。
2. **原文没讲的，直接说"这篇没有讲"**，不要用常识补一个听起来合理的答案冒充论文观点。
3. 说完之后，如果补充背景对理解有帮助，可以补 —— 但必须**另起一段并标明「背景补充（非本文内容）」**。
4. 问题里出现读者可能不熟的概念（专有名词、方法名、数据集、评价指标），**主动用一两句话解释清楚**，不要假设读者懂。这是读者明确要求的。
5. 不要复述摘要，不要说"这篇论文主要研究了……"这种正确的废话。直接回答被问的东西。
6. 篇幅克制：能三句话说清就不要写五段。读者要的是读懂这一处，不是一篇综述。

用中文回答，纯文本，不要 markdown 标题。`;
}

/**
 * 读后总结：把"划过的重点"和"论文主线"接起来。
 * 只做摘要没有意义 —— 关键是回答"我标的这些东西在这篇论文里是什么位置"。
 */
export function buildReadingSummaryPrompt({ title, context, annotations }) {
  const marks = annotations.length
    ? annotations.map((a, i) => {
      const tag = a.tag ? `[${a.tag}] ` : '';
      return `${i + 1}. ${tag}${a.quote ? `原文「${a.quote}」→ ` : ''}我的批注：${a.note}`;
    }).join('\n')
    : '（读者这次没有留下批注）';

  return `你在帮一个人整理刚读完的论文笔记。目标是让他合上论文之后**真的带走点东西**，而不是读完就忘。

论文：《${title}》
${FIELD_HINT}

论文内容（长文只截取了前面部分）：
<<<
${context}
>>>

读者读的时候标记的重点和批注：
${marks}

请输出一份读后总结。要求：
- **必须把读者的批注和论文主线接起来** —— 他标的这些点在论文里处于什么位置、为什么重要，或者哪些其实是枝节。这是这份总结最有价值的部分。
- 论文里没有明确说的，不要编。不确定就写"原文没有明说"。
- 每一条都要具体。禁止"该方法具有较好的效果"这类空话。

严格只输出一个 JSON 对象，不要解释，不要 markdown 代码块：
{"oneLine": "一句话说清这篇论文做了什么，让人半年后看到也能想起来",
 "problem": "它想解决的问题，以及为什么以前的做法不够",
 "method": "核心方法，讲清楚关键的那一步，不要罗列流程",
 "evidence": "拿什么证明有效：数据集、对比对象、关键数字",
 "yourMarks": "读者标记的那些点在论文里处于什么位置，哪些是主线、哪些是枝节",
 "limits": ["论文自己承认的或明显存在的局限"],
 "followUp": ["值得进一步查的问题，或读者批注里没解决的疑问"],
 "terms": [{"term": "文中出现的生僻概念", "plain": "用一两句大白话解释"}]}`;
}

