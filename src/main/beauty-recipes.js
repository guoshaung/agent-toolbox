'use strict';

// Independently generated configuration, based on the public consumers' INI contracts.
// No engine binary, hook code, artwork or registration logic is included.
const RECIPE_SOURCES = {
  dwm: 'https://github.com/Maplespe/DWMBlurGlass/blob/e3a160c849c35415a4b959462815eebc6870270b/Common/Common.cpp',
  explorer: 'https://github.com/Maplespe/ExplorerBlurMica/blob/5fd0b0b83b3564f7d51c9be966ec190f5e70f0f9/README_ZH.md',
};

function makeNativeRecipe(engine, profile) {
  if (!/^#[a-f0-9]{6}$/i.test(profile.tint) || !Number.isFinite(profile.opacity) || !Number.isFinite(profile.blur)) throw new Error('主题参数无效');
  const red = parseInt(profile.tint.slice(1, 3), 16);
  const green = parseInt(profile.tint.slice(3, 5), 16);
  const blue = parseInt(profile.tint.slice(5, 7), 16);
  const alpha = Math.round(Math.max(0, Math.min(100, profile.opacity)) * 255 / 100);
  const header = '; Generated by Agent Toolbox. Import manually into the matching engine.\r\n; This file does not install or enable an engine.\r\n';
  if (engine === 'dwm') {
    const effects = { glass: 0, acrylic: 2, mica: 3, solid: -1 };
    if (!(profile.effect in effects)) throw new Error('窗口质感无效');
    // Consumer uses Win32 COLORREF (0xAABBGGRR), written as an unsigned decimal.
    const blend = alpha * 0x1000000 + blue * 0x10000 + green * 0x100 + red;
    const values = { effectType: effects[profile.effect], blurMethod: 0, applyglobal: false,
      customAmount: true, blurAmount: Math.max(0, Math.min(50, profile.blur)), customBlurAmount: Math.max(0, Math.min(50, profile.blur)),
      activeBlendColor: blend, inactiveBlendColor: blend, activeBlendColorDark: blend, inactiveBlendColorDark: blend,
      useAccentColor: false, disableOnBattery: true, crossFade: true };
    return { engine, fileName: 'toolbox-dwmblurglass.ini', text: header + '[config]\r\n' + Object.entries(values).map(([key, value]) => `${key}=${value}`).join('\r\n') + '\r\n', source: RECIPE_SOURCES.dwm };
  }
  if (engine === 'explorer') {
    if (profile.effect === 'solid') throw new Error('ExplorerBlurMica 配方不支持纯色，请选择玻璃、亚克力或云母');
    const effects = { glass: 3, acrylic: 1, mica: 2 };
    if (!(profile.effect in effects)) throw new Error('窗口质感无效');
    const color = `r=${red}\r\ng=${green}\r\nb=${blue}\r\na=${alpha}\r\n`;
    return { engine, fileName: 'toolbox-explorerblurmica.ini', text: header + `[config]\r\neffect=${effects[profile.effect]}\r\nclearAddress=true\r\nclearBarBg=true\r\nclearWinUIBg=true\r\nshowLine=true\r\n[light]\r\n${color}[dark]\r\n${color}`, source: RECIPE_SOURCES.explorer };
  }
  throw new Error('不支持的原生引擎');
}

module.exports = { makeNativeRecipe, RECIPE_SOURCES };
